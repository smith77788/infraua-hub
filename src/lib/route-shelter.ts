import { distanceKm } from "./infra-types";
import type { Shelter } from "./shelters";

/**
 * Укриття вздовж дороги — і чесна відповідь про те, коли їх немає.
 *
 * ## Замір, який переписав задачу
 *
 * Задумувалось «показати укриття вздовж шляху». Замір на наявному наборі
 * (778 обʼєктів) по реальних маршрутах це спростував:
 *
 *   Київ — Львів (13 контрольних точок через 40 км):
 *     7 точок — жодного укриття в радіусі 60 км
 *     решта — найближче за 23, 36, 58, 72 км
 *   Київ — Харків (11 точок):
 *     4 точки — нічого; найближчі за 17, 38, 57, 60, 67 км
 *
 * Причина в самому наборі, а не в коді: 466 входів у метро й 184 підземні
 * паркінги — це міста. Між містами укриттів у наборі немає, бо їх там і в
 * житті майже немає.
 *
 * Укриття за 60 км — це година їзди. Назвати його «найближчим укриттям»
 * людині, у якої щойно завила тривога, означало б відправити її їхати годину
 * під нальотом. Тому поріг жорсткий, а коли нічого не підходить — так і
 * кажемо, замість того щоб показати найкраще з поганого.
 */

/**
 * Скільки ще має сенс їхати до укриття, км.
 *
 * ~20 хвилин на міжміській швидкості. Далі це вже не «сховатись», а «доїхати
 * кудись», і рішення в людини інше.
 */
export const SHELTER_REACH_KM = 25;

export interface LegShelter {
  /** Скільки кілометрів від початку маршруту припадає на цю ділянку. */
  fromStartKm: number;
  /** Найближче укриття в межах порога — або `null`, коли такого немає. */
  shelter: { name: string; km: number } | null;
}

/**
 * Найближче укриття до точки — лише в межах порога.
 *
 * `lookup` віддає укриття-кандидати (звичайно з локального набору за рамкою);
 * мережі тут немає навмисно, бо це аварійна функція.
 */
export function shelterNear(
  point: { lat: number; lon: number },
  lookup: (p: { lat: number; lon: number }) => readonly Shelter[],
  reachKm = SHELTER_REACH_KM,
): { name: string; km: number } | null {
  let best: { name: string; km: number } | null = null;
  for (const s of lookup(point)) {
    const km = distanceKm(point, s);
    if (!Number.isFinite(km) || km > reachKm) continue;
    if (!best || km < best.km) best = { name: s.name, km: Math.round(km) };
  }
  return best;
}

/**
 * Рядок про укриття для НЕБЕЗПЕЧНИХ ділянок маршруту.
 *
 * Тільки для них: перелік укриттів уздовж усього спокійного шляху — це шум,
 * який ховає єдиний рядок, що справді важить.
 */
export function renderRouteShelters(legs: readonly LegShelter[]): string | null {
  if (legs.length === 0) return null;
  const withShelter = legs.filter((l) => l.shelter !== null);
  const lines: string[] = ["", "🛡 <b>Де сховатись на небезпечних ділянках</b>"];
  for (const l of legs) {
    lines.push(
      l.shelter
        ? `• ${l.fromStartKm} км — ${l.shelter.name} (${l.shelter.km} км убік)`
        : `• ${l.fromStartKm} км — укриття поблизу немає`,
    );
  }
  if (withShelter.length < legs.length) {
    /*
     * Порада для ділянки без укриття — не заповнювач порожнечі, а єдина
     * правильна відповідь. Між містами укриттів немає, і людині потрібно
     * знати, що робити саме там, а не їхати годину до найближчого метро.
     */
    lines.push(
      "",
      "<i>Між містами укриттів немає — і це не прогалина наших даних, а стан",
      "речей. Якщо тривога застала в дорозі: зупиніться, вийдіть із машини й",
      "лягайте в канаву чи заглиблення подалі від автомобіля. Машина — не",
      "захист, а помітна ціль.</i>",
    );
  }
  return lines.join("\n");
}
