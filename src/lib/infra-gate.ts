/**
 * Один вимикач для всіх шарів критичної інфраструктури України.
 *
 * Консоль будувалася навколо карти обʼєктів: підстанції, електростанції,
 * лінії передачі, а поверх них — рейтинг критичності, розбір відмов і
 * кореляція загроз. Разом це відповідь на питання «який обʼєкт вивести з ладу,
 * щоб наслідки були найбільшими», і в публічному доступі вона корисна не лише
 * тому, хто відновлює мережу.
 *
 * Тому в продакшні шарів немає. Не сховані — **не віддаються**.
 *
 * ## Чому вимикач читається на сервері, а не вбудовується у збірку
 *
 * Дані по обʼєктах приходять виключно через серверні функції: браузер ніколи
 * не ходить до Overpass сам. Отже, достатньо, щоб відмовляв сервер, — і це
 * сильніша гарантія, ніж прапорець у клієнтському бандлі. Клієнтський
 * прапорець вимикає малювання; серверний вимикає саме існування даних по той
 * бік HTTP. Перше обходиться інструментами розробника, друге — ні.
 *
 * Опорний перелік обʼєктів (`infra-seed.ts`) з тієї ж причини вантажиться
 * динамічним імпортом усередині обробника: інакше він потрапив би в
 * клієнтський бандл як звичайний масив і їхав би до кожного відвідувача
 * незалежно від того, чи його хтось запитував.
 *
 * ## Як увімкнути локально
 *
 * `INFRA_LAYERS=on npm run dev` — для роботи над цим кодом. Будь-яке інше
 * значення, як і відсутність змінної, лишає шари вимкненими: усталене
 * значення помиляється в бік «не віддавати».
 */

export const INFRA_LAYERS_FLAG = "INFRA_LAYERS";

/**
 * Чи віддавати обʼєкти інфраструктури цьому запиту.
 *
 * Читається на кожному виклику, а не один раз при старті модуля: збірка йде
 * під Cloudflare Workers, де модульний стан живе в межах ізоляту, і значення,
 * обчислене при завантаженні модуля, означало б різну поведінку в різних
 * ізолятах після зміни змінної оточення.
 */
/** Дозвіл розгортання: без нього шарів немає ніколи. */
export function infraLayersPermitted(): boolean {
  return process.env[INFRA_LAYERS_FLAG] === "on";
}

/**
 * Скільки триматися за відповідь платформи, мс.
 *
 * Вимикач крутять руками, не автоматом, тож півхвилини затримки прийнятні, а
 * запит до Railway на кожен показ карти — ні.
 */
const CACHE_MS = 30_000;

let cached: { value: boolean; at: number } | null = null;

/**
 * Чи віддавати обʼєкти інфраструктури просто зараз.
 *
 * Дозвіл читається з оточення, положення ручки — з платформи, бо консоль живе
 * на Workers і власного диска не має: змінну оточення бот змінити не може, а
 * стан має переживати рестарт і бути спільним для обох половин системи.
 *
 * **Недоступна платформа означає «вимкнено».** Це свідомий обмін: збій звʼязку
 * ховає шари, замість того щоб лишити їх увімкненими тоді, коли ніхто не може
 * їх вимкнути. Вимикач, який заклинює в положенні «увімкнено», гірший за його
 * відсутність.
 *
 * Якщо платформа взагалі не налаштована, лишається сам дозвіл: розгортання без
 * платформи — штатний стан, і воно керується змінною оточення, як і раніше.
 */
export async function infraLayersEnabled(): Promise<boolean> {
  if (!infraLayersPermitted()) return false;

  const { isPlatformConfigured, platformFetch } = await import("./platform-client");
  if (!isPlatformConfigured()) return true;

  const now = Date.now();
  if (cached && now - cached.at < CACHE_MS) return cached.value;

  try {
    const res = await platformFetch("/api/platform/settings/infra-layers", { method: "GET" });
    const body = res.body as { switchedOn?: boolean } | null;
    // `switchedOn`, а не `enabled`: платформа рахує «enabled» з урахуванням
    // **свого** дозволу, а він тут ні до чого — консоль має власний.
    const value = res.ok && body?.switchedOn === true;
    cached = { value, at: now };
    return value;
  } catch {
    cached = { value: false, at: now };
    return false;
  }
}

/** Тільки для тестів і для негайного застосування після оберту ручки. */
export function forgetInfraLayersCache(): void {
  cached = null;
}

/**
 * Причина, яку бачить консоль, коли шарів немає.
 *
 * Порожній набір без пояснення читається як «джерело не відповідає», і далі
 * хтось чесно намагається полагодити те, що вимкнули навмисно.
 */
export const INFRA_DISABLED_NOTICE = "Шари критичної інфраструктури вимкнені в цьому розгортанні.";

/**
 * Як консоль читає стан із відповіді сервера.
 *
 * Станів три, і третій — головний: `true` — вимкнено, `false` — увімкнено,
 * поля немає — відповіді ще немає. Останнє трактується як вимкнено, бо
 * сторінка збирається на сервері до того, як запит устигне відповісти: інакше
 * був би кадр, у якому вся обстановка шарів уже намальована, і лише потім
 * зникала б.
 *
 * Саме тому увімкнений шлях проставляє `disabled: false` явно, а не лишає
 * поле порожнім: інакше він був би невідрізненним від «ще не відповіли», і
 * вимикач не вмикався б назад — так це вперше й зламалося.
 */
export function infraLayersOff(payload: { disabled?: boolean } | undefined): boolean {
  return payload?.disabled !== false;
}
