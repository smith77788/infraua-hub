/**
 * Поріг «будити за N хвилин льоту», а не лише за радіусом.
 *
 * Радіус — груба міра терміновості. Шахед за 50 км — це пів години часу;
 * балістика за ті самі 50 км — менш ніж хвилина. Людина, яка виставила радіус
 * «50 км», насправді хотіла сказати не про кілометри, а про запас часу дійти
 * до укриття. Поріг за часом підльоту дає саме це: швидка ціль будить далі,
 * повільна — ближче, а запас часу лишається тим самим, який людина обрала.
 *
 * Це НАДБУДОВА над радіусом, а не заміна: радіус усе ще відсікає далеке, а поріг
 * усередині нього вирішує, чи вже пора. Коли поріг не заданий — усе працює як
 * раніше. Коли ціль підходить, а часу підльоту оцінити не вдалося (немає курсу),
 * поріг НЕ мовчить: невідомий час — привід попередити, а не привід проґавити.
 *
 * Чиста функція: жодного стану, лише число проти числа.
 */

/** Межі осмисленого запасу часу, хв. */
export const LEAD_MIN = 2;
export const LEAD_MAX = 30;

/** Розбір значення з кнопки/команди. Поза межами — найближча межа, не помилка. */
export function clampLead(min: number): number {
  if (!Number.isFinite(min)) return LEAD_MIN;
  return Math.max(LEAD_MIN, Math.min(LEAD_MAX, Math.round(min)));
}

export interface LeadDecision {
  /** Чи всередині обраного вікна часу (або поріг вимкнено). */
  within: boolean;
  /** Найбезпечніший (найраніший) оцінений час підльоту, хв, або `null`. */
  etaLowMin: number | null;
  reason: string;
}

/**
 * Чи вкладається найближча вхідна ціль у поріг часу підльоту.
 *
 * `etaLowMin` — НАЙБЕЗПЕЧНІШЕ прочитання часу до найближчої вхідної (нижній
 * край вилки: ціль може бути ближчою, ніж її позначка). Саме він, а не середнє,
 * порівнюється з порогом — та сама асиметрія, що в усій системі: поспішити
 * безпечно, запізнитися ні.
 *
 * `leadMin == null` — поріг вимкнено: `within: true`, хай вирішує радіус.
 */
export function withinLead(
  etaLowMin: number | null,
  leadMin: number | null | undefined,
): LeadDecision {
  if (leadMin == null) {
    return { within: true, etaLowMin, reason: "поріг часу вимкнено" };
  }
  const lead = clampLead(leadMin);
  if (etaLowMin == null) {
    // Ціль іде на точку, але час підльоту оцінити не вдалося (немає курсу чи
    // швидкості). Мовчати тут означало б проґавити швидку ціль без телеметрії.
    return { within: true, etaLowMin: null, reason: "час підльоту невідомий — не ризикуємо" };
  }
  const within = etaLowMin <= lead;
  return {
    within,
    etaLowMin,
    reason: within
      ? `до підльоту ≤ ${lead} хв (оцінка ${etaLowMin} хв)`
      : `ще є час: ~${etaLowMin} хв, поріг ${lead} хв`,
  };
}

/**
 * Пояснення порога людською мовою.
 *
 * Тут навмисно названо не «швидше/повільніше», а саме запас часу: кілометри
 * однакові для шахеда й для балістики, а хвилини — ні, і саме хвилини людина
 * мала на увазі, коли крутила радіус.
 */
export function renderLeadHelp(current: number | null): string {
  return [
    "⏱ <b>Будити за запасом часу</b>",
    "",
    current === null
      ? "Зараз: <b>будь-яка вхідна ціль у радіусі</b>."
      : `Зараз: <b>${current} хв льоту</b> — раніше не турбуємо.`,
    "",
    "Радіус міряє кілометри, а дійти до укриття ви встигаєте за хвилини. Шахед за",
    "50 км — це пів години часу; балістика за ті самі 50 км — менш ніж хвилина.",
    "Поріг за часом лишає вам однаковий запас незалежно від того, що летить.",
    "",
    `<code>/lead 10</code> — будити, коли до підльоту лишилось ≤ 10 хв (${LEAD_MIN}–${LEAD_MAX}).`,
    "<code>/lead вимк</code> — повернути звичайний поріг за радіусом.",
    "",
    "<i>Коли час підльоту оцінити не вдалося — немає курсу чи швидкості — поріг",
    "вас не відсікає: невідомий час це привід попередити, а не проґавити.</i>",
  ].join("\n");
}

/** Підтвердження збереженого порога. */
export function renderLeadSaved(value: number | null): string {
  if (value === null) {
    return [
      "✅ Поріг часу вимкнено.",
      "",
      "Будимо знову за будь-якої вхідної цілі в радіусі — як було.",
    ].join("\n");
  }
  return [
    `✅ Будимо, коли до підльоту лишається <b>≤ ${value} хв</b>.`,
    "",
    "Радіус працює далі: він відсікає далеке, а поріг усередині нього вирішує, коли",
    "саме пора. Далека повільна ціль тепер вас не розбудить — швидка розбудить раніше.",
    "",
    "/settings — решта налаштувань",
  ].join("\n");
}
