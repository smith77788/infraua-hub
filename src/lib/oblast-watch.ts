/**
 * Офіційна тривога для МОЄЇ області — те, чого бот не вмів найдовше.
 *
 * Дивна прогалина: радар рахував траєкторії, промахи й шанси, вмів
 * передтривогу — і жодного разу не сказав людині найпростішого, заради чого
 * вмикають будь-який інший бот: «у вашій області оголошено тривогу». Ми цю
 * подію бачили (стрічка офіційних тривог опитується щохвилини), використовували
 * її для відбою в каналі — і не доносили до того, кого вона стосується.
 *
 * ## Чому це окремий клас сповіщення
 *
 * Наші попередження — оцінка: ми бачимо ціль і рахуємо, куди вона йде.
 * Офіційна тривога — факт: її оголосили Повітряні Сили. Це різні речі, і
 * плутати їх не можна ні в текстах, ні в налаштуваннях: людина може не хотіти
 * наших оцінок і хотіти офіційних тривог, або навпаки.
 *
 * ## Що саме тут
 *
 * Чисте порівняння двох станів стрічки: які області щойно СТАЛИ тривожними, а
 * які щойно перестали. Жодної мережі, жодного годинника — тому поведінку на
 * зміні стану видно тестом, а не спостереженням за живим ботом.
 */

export interface OblastTransition {
  oblast: string;
  kind: "started" | "cleared";
}

/**
 * Що змінилось у стрічці офіційних тривог.
 *
 * `previous === null` означає «перший знімок»: переходів немає. Це важливо —
 * інакше перший запуск процесу розіслав би «оголошено тривогу» всім, у кого
 * вона вже тривала годину, і кожен редеплой перетворювався б на хибну сирену.
 */
export function oblastTransitions(
  previous: readonly string[] | null,
  current: readonly string[],
): OblastTransition[] {
  if (previous === null) return [];
  const before = new Set(previous);
  const now = new Set(current);
  const out: OblastTransition[] = [];
  for (const o of now) if (!before.has(o)) out.push({ oblast: o, kind: "started" });
  for (const o of before) if (!now.has(o)) out.push({ oblast: o, kind: "cleared" });
  return out.sort((a, b) => a.oblast.localeCompare(b.oblast, "uk"));
}

/**
 * Текст початку тривоги.
 *
 * Джерело названо в першому рядку навмисно. Людина має за секунду зрозуміти,
 * що це не наша оцінка, а оголошення — від цього залежить, наскільки швидко
 * вона встане.
 */
export function renderAlertStarted(oblast: string, places: readonly string[]): string {
  const where = places.length > 1 ? `\nВаші місця в цій області: ${places.join(", ")}` : "";
  return [
    `🔴 <b>Повітряна тривога — ${oblast}</b>`,
    "",
    `Оголошено офіційно.${where}`,
    "",
    "<i>Це офіційна тривога, а не наша оцінка. Пройдіть в укриття.</i>",
  ].join("\n");
}

/**
 * Текст відбою.
 *
 * Єдине місце в усій системі, де слово «відбій» вживається без застережень, —
 * бо тут це справді відбій: його оголосили, а не ми перестали бачити цілі.
 */
export function renderAlertCleared(oblast: string, durationText: string | null): string {
  return [
    `🟢 <b>Відбій — ${oblast}</b>`,
    "",
    durationText ? `Тривога тривала ${durationText}.` : "Офіційну тривогу знято.",
    "",
    "<i>Відбій офіційний.</i>",
  ].join("\n");
}

/**
 * Стан тривог для тривалості.
 *
 * Тримається окремо від самого переліку, бо відповідає на інше питання: не
 * «чи триває», а «відколи». Без цього відбій не міг би сказати «тривала
 * 2 год 15 хв» — а саме це число люди й пересилають одне одному.
 */
export function updateAlertStarts(
  starts: ReadonlyMap<string, number>,
  current: readonly string[],
  now: number,
): Map<string, number> {
  const next = new Map<string, number>();
  for (const o of current) next.set(o, starts.get(o) ?? now);
  return next;
}
