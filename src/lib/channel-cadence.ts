import type { ThreatType } from "./air";

/**
 * Коли канал має озватися — і чи новим постом, чи правкою живого.
 *
 * Це рішення — найпомітніша для читача поведінка бота, і доти воно жило
 * всередині `runChannelTickCore`, сплетене з Telegram, рендером картинки та
 * читанням фіду. Через це його не можна було ні перевірити тестом, ні
 * заміряти: питання «а як часто бот постить під час нальоту?» вимагало
 * справжнього нальоту. Тут воно чисте: на вході — числа, на виході — дія.
 *
 * Правила тримаються на одній асиметрії. ПРАВКА живого поста нікого не
 * турбує: у стрічці нічого не зʼявляється, сповіщення не приходить, читач
 * просто бачить свіжіший текст, коли сам подивиться. НОВИЙ пост — це дзвінок
 * у кишені. Тому поріг нового поста високий, а правки — низький.
 */

/** Найменший проміжок між двома дотиками до каналу (пост або правка). */
export const MIN_TOUCH_MS = 4 * 60 * 1000;

/**
 * Скільки живий пост може мовчати, перш ніж його торкнуться заради ознаки
 * життя. Читач, який бачить пост «оновлено 40 хв тому» під час нальоту, не
 * може відрізнити «нічого не змінилось» від «бот помер».
 */
export const HEARTBEAT_MS = 25 * 60 * 1000;

/**
 * Скільки живий пост лишається живим. Далі його ховає стрічка: редагувати
 * поховане — означає лишити читачів на новіших повідомленнях без картини.
 */
export const LIVE_POST_MAX_MS = 45 * 60 * 1000;

export interface CadenceInput {
  now: number;
  /** Підпис поточного зрізу неба. */
  signature: string;
  /** Підпис того, що вже лежить у каналі. */
  lastSignature: string;
  /** Коли востаннє щось робили в каналі — пост АБО правка. */
  lastTouchAt: number;
  /** Коли створили живий пост. Правки цей час не зсувають. */
  livePostAt: number;
  /** Id живого поста; null — живого немає, редагувати нічого. */
  messageId: number | null;
  /** Критичні типи, яких за цю хвилю ще не бачили. */
  escalation: readonly ThreatType[];
  /** Ручний виклик (`/channel`) — проходить повз усі пороги. */
  force?: boolean;
}

export type CadenceDecision =
  | { action: "silent"; reason: string }
  | { action: "edit"; reason: string }
  | { action: "post"; reason: string };

export function decideChannelAction(input: CadenceInput): CadenceDecision {
  const { now, force = false } = input;
  const changed = input.signature !== input.lastSignature;
  const escalated = input.escalation.length > 0;

  /*
   * Ручний виклик завжди дає НОВИЙ пост, а не правку.
   *
   * `/channel` — команда власника «скажи зараз». Тихо відредагувати пост,
   * похований у стрічці, — не те, про що просили: людина смикає команду саме
   * тоді, коли хоче, щоб канал озвався.
   */
  if (force) return { action: "post", reason: "викликано вручну" };

  /*
   * Ескалація перевіряється ПЕРШОЮ — раніше за будь-який поріг тиші.
   *
   * Спершу вона стояла після гейта «нічого не змінилось», і це виявив тест:
   * новий критичний тип при незмінному підписі проковтувався мовчки. У фіді
   * такий збіг рідкісний (новий тип зазвичай міняє й підпис), але «рідкісний»
   * — не «неможливий», а ціна помилки тут несиметрична: пропущена правка
   * коштує несвіжого числа, пропереджене попередження про балістику коштує
   * людей. Тому жоден поріг тиші не стоїть перед цією перевіркою.
   */
  if (escalated) {
    return { action: "post", reason: `нова загроза: ${input.escalation.join(", ")}` };
  }

  // Нічого не змінилось і ознака життя ще свіжа — говорити нема про що.
  const heartbeatDue = now - input.lastTouchAt >= HEARTBEAT_MS;
  if (!changed && !heartbeatDue) return { action: "silent", reason: "без суттєвих змін" };

  /*
   * Поріг частоти. Тик смикає не один планувальник: внутрішній таймер,
   * зовнішній крон через `/api/channel-tick`, команда `/channel`, а після
   * редеплою — ще й прогрів одразу по старту. Кожен із них сам по собі
   * розумний, разом вони дають частоту, якої не задавав ніхто.
   */
  if (now - input.lastTouchAt < MIN_TOUCH_MS) {
    return { action: "silent", reason: "щойно оновлювали" };
  }

  return decideShape(input, changed ? "картина змінилась" : "ознака життя");
}

function decideShape(input: CadenceInput, why: string): CadenceDecision {
  if (input.messageId === null) return { action: "post", reason: "немає живого поста" };
  if (input.now - input.livePostAt > LIVE_POST_MAX_MS) {
    return { action: "post", reason: "живий пост застарів" };
  }
  return { action: "edit", reason: why };
}
