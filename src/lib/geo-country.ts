/**
 * У якій країні стоїть точка людини — заміряне, а не виведене з відстані.
 *
 * ПРОБЛЕМА. `oblastOf` повертає НАЙБЛИЖЧИЙ обласний центр без жодного
 * обмеження відстані. Заміряно: точка в Торонто дає «Закарпаття», у Берліні —
 * теж «Закарпаття», у Варшаві — «Львівщина». Тобто людині за кордоном
 * показувалась тривога чужої області як її власна.
 *
 * ЧОМУ НЕ ПОРОГОМ ВІДСТАНІ. Перше, що спадає на думку, — відсікати за
 * кілометрами. Замір це спростував: Рені (Україна) — 221 км від найближчого
 * обласного центру, а Перемишль (Польща) — 91 км. Будь-який єдиний поріг або
 * відрізає українські міста, або впускає закордонні. Розділити їх відстанню
 * неможливо в принципі, бо обласні центри розставлені нерівномірно.
 *
 * ЩО РОБИМО НАТОМІСТЬ. Питаємо джерело, яке знає кордони: зворотне
 * геокодування OSM (Nominatim). Це один запит на момент, коли людина ЗАДАЄ
 * точку, а не на кожне сповіщення: точка не переїжджає між країнами, тож
 * відповідь кешується в підписці назавжди.
 *
 * Тут — лише чистий розбір відповіді й побудова адреси. Мережа лишається в
 * server.ts, щоб це можна було перевірити тестом без інтернету.
 */

/** Код країни за ISO 3166-1 alpha-2, малими літерами. */
export type CountryCode = string;

export interface PlaceCountry {
  /** `ua`, `pl`, `ca`… `null` — джерело відповіло, але країни не назвало. */
  countryCode: CountryCode | null;
  /** Назва регіону так, як її дає OSM: «Одеська область», «Ontario». */
  state: string | null;
}

/**
 * Адреса зворотного геокодування.
 *
 * `zoom=5` — рівень області/штату: цього досить, щоб дізнатись країну й регіон,
 * і не тягне зайвих подробиць про будинок. Адресу людини ми не питаємо й не
 * зберігаємо: питання рівно одне — «це Україна чи ні».
 */
export function reverseGeocodeUrl(lat: number, lon: number): string {
  const la = Number.isFinite(lat) ? lat : 0;
  const lo = Number.isFinite(lon) ? lon : 0;
  return (
    "https://nominatim.openstreetmap.org/reverse?format=jsonv2" +
    `&lat=${la.toFixed(5)}&lon=${lo.toFixed(5)}&zoom=5`
  );
}

/**
 * Розбирає відповідь Nominatim. Будь-яка несподіванка — `null`, а не здогад:
 * «не знаємо країни» і «країна не Україна» мають різні наслідки, і плутати їх
 * не можна.
 */
export function parseReverseGeocode(raw: unknown): PlaceCountry | null {
  if (!raw || typeof raw !== "object") return null;
  const address = (raw as { address?: unknown }).address;
  if (!address || typeof address !== "object") return null;
  const a = address as Record<string, unknown>;
  const code = typeof a["country_code"] === "string" ? a["country_code"].toLowerCase() : null;
  const state =
    typeof a["state"] === "string"
      ? a["state"]
      : typeof a["country"] === "string"
        ? a["country"]
        : null;
  if (code === null && state === null) return null;
  return { countryCode: code, state };
}

/**
 * Чи точка в Україні — з ТРЬОМА відповідями, а не двома.
 *
 * `null` («не знаємо») навмисно окремий від `false`. Для старих підписок, які
 * задали точку до появи цієї перевірки, країна невідома, і повестися з ними
 * як із закордонними означало б мовчки відібрати тривоги в людей удома.
 */
export function isInUkraine(country: string | null | undefined): boolean | null {
  if (country === undefined || country === null || country === "") return null;
  return country === "ua";
}

/**
 * Рядок для того, хто стежить із-за кордону.
 *
 * Без нього людина за кордоном бачить порожній радар і вирішує, що бот
 * зламався: цілей у радіусі навколо Варшави справді немає, а чому — ніде не
 * сказано. Пояснюємо й одразу кажемо, що робити далі: стежити не за собою, а
 * за своїми.
 */
export function renderAbroadNotice(): string {
  return [
    "",
    "🌍 <b>Ваша точка — за межами України.</b>",
    "Офіційні тривоги тут не показуємо: у вашій країні інша система оповіщення,",
    "і видавати за неї українську сирену було б неправдою.",
    "",
    "Але радар вам однаково є для чого: додайте місця, за які хвилюєтесь, —",
    "<code>/place мама Харків</code>, <code>/place дім Київ</code> — і бот",
    "повідомлятиме про них, а не про вас.",
  ].join("\n");
}
