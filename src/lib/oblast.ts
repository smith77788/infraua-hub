const NORMALIZED = OBLASTS.map((o) => ({ ...o, norm: o.stems.map(normName) }));

/**
 * Основи ІМЕННИКІВ-назв областей: «-щина», Буковина, Волинь, Закарпаття.
 *
 * Прикметникові основи («-ськ», «-цьк») сюди НЕ входять свідомо: вони
 * збігаються з назвами міст — «Хмельницький», «Донецьк», «Луганськ». Курс «на
 * Хмельницький» — це місто, і загубити його не можна.
 */
const REGION_NOUN_STEMS = NORMALIZED.flatMap((o) =>
  o.norm.filter((s) => /щин$|^буковин|^волин|^закарпат|^прикарпат/.test(s)),
);

/**
 * Чи це назва ОБЛАСТІ в будь-якому відмінку («Харківщині», «Харківщину»,
 * «Буковина»), а не пункт.
 *
 * У довіднику є села з такими назвами — Харківщина (Сумщина), Буковина, — і
 * «2 реактиви на Харківщині у бік Полтави» ставило ціль у сумське село за
 * півтори сотні кілометрів від Харкова. Заміряно 25.10 на остаточних точках
 * 111 каналів: 4 рази, з трьох каналів (PoltavaRanger, monitor_ukr,
 * radar_raketaa). Канал, що пише «Харківщина», завжди має на увазі область.
 *
 * Хвіст після основи — не довший за три літери: інакше під «волин»
 * потрапили б «Волинцеве» та інші справжні села.
 */
export function isRegionName(said: string): boolean {
  const w = normName(said)
    .replace(/[^\p{L}\s]/gu, " ")
    .trim();
  if (!w || /\s/.test(w)) return false;
  return REGION_NOUN_STEMS.some((s) => w.startsWith(s) && w.length - s.length <= 3);
}
const cache = new WeakMap<Gazetteer, Map<number, string | null>>();

/**
 * Код області (`admin1` довідника), у МЕЖАХ якої лежить місце з рядка, або
 * `null`.
 *
 * Лише два вжитки кажуть «місце тут»: заголовок («Житомирщина: …»,
 * «Рівненщина - …») і місцевий відмінок («на Полтавщині», «у Київській
 * області»). «З Житомирщини курсом на Фастів», «на Полтавщину» — звідки чи
 * куди, а не де: такий рядок області не обмежує.
 */
export function oblastAdminIn(line: string, gaz: Gazetteer): string | null {
  const n = normName(line.replace(/^[^\p{L}]+/u, ""));
  let found = -1;
  NORMALIZED.forEach((o, i) => {
    if (found >= 0) return;
    for (const s of o.norm) {
      const k = n.indexOf(s);
      if (k < 0 || (k > 0 && /[\p{L}]/u.test(n[k - 1]!))) continue;
      const word = n.slice(k).split(" ")[0]!;
      const header = k === 0;
      const before = n.slice(Math.max(0, k - 3), k);
      // «полтавщині» після нормалізації — «полтавщини», як і родовий «з
      // Полтавщини»; розрізняє їх лише прийменник.
      const locative = /(?:^|\s)(?:на|у|в) $/.test(before) && /(?:ини|скии|ии|ин)$/.test(word);
      if (header || locative) {
        found = i;
        return;
      }
    }
  });
  if (found < 0) return null;
  let m = cache.get(gaz);
  if (!m) cache.set(gaz, (m = new Map()));
  if (!m.has(found)) {
    const o = NORMALIZED[found]!;
    m.set(found, gaz.adminNear(o.lat, o.lon));
  }
  return m.get(found) ?? null;
}

/**
 * Область як НАПРЯМОК: «повз Овруч у Рівненську область», «на Київщину», «в
 * бік Волині», «до Житомирщини». Повертає точку, куди дивиться курс, — центр
 * області (обласний центр: для напрямку з сусідньої області цього досить).
 *
 * Заміряно 28.10, monikppy: «Реактивний на Овруч / Реактивний повз Овруч у
 * Рівненську область». Без цього єдиним курсом лишалось «на Овруч» — у ту
 * саму точку, де ціль уже була, — і значок дивився на північ, хоча ціль ішла
 * на захід.
 *
 * Не напрямок: заголовок («Житомирщина: …»), місцевий відмінок («на
 * Полтавщині») і походження («з Брянщини», «з Житомирщини»).
 */
export function oblastDirectionIn(line: string): { lat: number; lon: number } | null {
  const n = normName(line);
  for (const o of NORMALIZED) {
    for (const s of o.norm) {
      let k = n.indexOf(s);
      while (k >= 0) {
        if (k === 0 || !/[\p{L}]/u.test(n[k - 1]!)) {
          const word = n.slice(k).split(" ")[0]!;
          const before = n.slice(Math.max(0, k - 14), k);
          const toward = /(?:^|\s)(?:до|в бик|у бик|в напрямку|у напрямку) $/.test(before);
          const into = /(?:^|\s)(?:у|в|на) $/.test(before) && /у$/.test(word);
          if (toward || into) return { lat: o.lat, lon: o.lon };
        }
        k = n.indexOf(s, k + 1);
      }
    }
  }
  return null;
}
