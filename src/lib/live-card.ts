import type { DangerLevel } from "./advisory";

/**
 * Жива картка тривоги: одне повідомлення, яке правиться, замість потоку.
 *
 * ПРОБЛЕМА. За двогодинний наліт людина отримує до півтора десятка окремих
 * повідомлень: поріг у чотири хвилини й пауза у вісім хвилин стримують, але
 * кожна НОВА вхідна ціль паузу пробиває, а нових цілей у налеті багато.
 * Розмова з ботом перетворюється на стрічку, у якій свіже не відрізнити від
 * застарілого, і найгірше — де серед десяти однакових рядків та єдина зміна,
 * заради якої все це існує.
 *
 * ЧОМУ ЦЕ НЕ МОЖНА ВВІМКНУТИ ВСІМ. Правка повідомлення в Telegram НЕ дає
 * сповіщення. Людина, яка відклала телефон після першого «готовність», про
 * нові цілі не почує — вона побачить їх, лише коли сама відкриє чат. Нинішня
 * поведінка будить її навмисно. Міняти це за людину означало б віддати її
 * безпеку за чужу скаргу на потік, тож режим лише на вибір, а усталеним
 * лишається потік.
 *
 * ЩО ЗАЛИШАЄТЬСЯ ГУЧНИМ У БУДЬ-ЯКОМУ РАЗІ. Загострення — зростання рівня
 * небезпеки — завжди йде ОКРЕМИМ повідомленням зі звуком, навіть коли картка
 * ввімкнена. Саме той момент, заради якого бота тримають, ніколи не стає
 * тихою правкою.
 */

/** Стан живої картки людини. */
export interface LiveCard {
  messageId: number;
  /** Коли картку СТВОРИЛИ. Правки цей час не зсувають. */
  at: number;
  /** Рівень, на якому картку відкрили — з ним порівнюється загострення. */
  level: DangerLevel;
}

/**
 * Скільки картка лишається придатною для правки.
 *
 * Далі її ховає переписка: у чаті з ботом між тим повідомленням і низом екрана
 * вже підсумок доби, відбій і відповіді на команди. Правити поховане — те саме,
 * що не сказати нічого.
 */
export const CARD_MAX_MS = 45 * 60 * 1000;

const LEVEL_RANK: Record<DangerLevel, number> = { calm: 0, watch: 1, attention: 2, shelter: 3 };

export type CardAction =
  { action: "send"; reason: string } | { action: "edit"; messageId: number; reason: string };

export interface CardInput {
  /** Чи ввімкнула людина режим живої картки. */
  enabled: boolean;
  card: LiveCard | null | undefined;
  level: DangerLevel;
  now: number;
}

export function decideCardAction(input: CardInput): CardAction {
  const { enabled, card, level, now } = input;
  if (!enabled) return { action: "send", reason: "режим живої картки вимкнено" };
  if (!card) return { action: "send", reason: "картки ще немає" };
  if (LEVEL_RANK[level] > LEVEL_RANK[card.level]) {
    // Загострення завжди зі звуком: тиха правка тут коштувала б саме того,
    // заради чого все це працює.
    return { action: "send", reason: "обстановка загострилась" };
  }
  if (now - card.at > CARD_MAX_MS) {
    return { action: "send", reason: "картку поховала переписка" };
  }
  return { action: "edit", messageId: card.messageId, reason: "оновлюємо живу картку" };
}

/**
 * Стан картки після вдалої відправки чи правки.
 *
 * Рівень картки НЕ знижується при правці: картка, відкрита на «в укриття» й
 * виправлена до «готовність», лишається карткою рівня «в укриття». Інакше
 * повернення до «в укриття» не зарахувалось би як загострення і прийшло б
 * тихою правкою — рівно та помилка, якої цей модуль уникає.
 */
export function cardAfter(
  prev: LiveCard | null | undefined,
  decision: CardAction,
  level: DangerLevel,
  now: number,
  messageId: number,
): LiveCard {
  if (decision.action === "send") return { messageId, at: now, level };
  const keep = prev && LEVEL_RANK[prev.level] >= LEVEL_RANK[level] ? prev.level : level;
  return { messageId: decision.messageId, at: prev?.at ?? now, level: keep };
}

/**
 * Картка після відбою — її треба закрити, щоб наступна хвиля відкрила нову.
 *
 * Без цього картка хвилі, що скінчилась годину тому, ловила б правки наступної
 * хвилі й ховала б їх у вчорашній переписці.
 */
export function closeCard(): null {
  return null;
}

/** Пояснення режиму — і його ціни. Людина має обирати, знаючи обидва боки. */
export function renderCardHelp(enabled: boolean): string {
  return [
    enabled ? "🗂 <b>Жива картка: увімкнено</b>" : "🗂 <b>Жива картка: вимкнено</b>",
    "",
    "За довгий наліт бот шле десяток окремих повідомлень — по одному на кожну",
    "нову ціль. У режимі живої картки він замість цього <b>переписує одне</b>:",
    "у чаті лишається один рядок, і він завжди свіжий.",
    "",
    "⚠️ <b>Ціна режиму.</b> Правка повідомлення не дає сповіщення. Якщо ви",
    "відклали телефон, про нові цілі ви <b>не почуєте</b> — побачите, коли самі",
    "відкриєте чат.",
    "",
    "✅ <b>Що лишається гучним.</b> Загострення — коли небезпека зростає —",
    "завжди приходить окремим повідомленням зі звуком. І перше сповіщення",
    "кожної нової тривоги теж.",
    "",
    enabled ? "Вимкнути: <code>/картка вимк</code>" : "Увімкнути: <code>/картка увімк</code>",
  ].join("\n");
}

export function renderCardSaved(enabled: boolean): string {
  return enabled
    ? [
        "🗂 Увімкнено. Під час нальоту оновлення приходитимуть у одне повідомлення.",
        "",
        "Звук лишається за загостренням і за першим сповіщенням тривоги.",
      ].join("\n")
    : "🔔 Вимкнено. Кожна зміна знову приходитиме окремим повідомленням.";
}
