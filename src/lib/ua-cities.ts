/** Центри всіх областей (по одному на код) — «вся область», коли міста замало. */
export const OBLAST_CENTERS: readonly Place[] = Object.values(OBLASTS)
  .filter((o, i, arr) => arr.findIndex((x) => x.code === o.code) === i)
  .map((o) => ({ name: o.name, lat: o.lat, lon: o.lon }));

/**
 * Усі місця для вибору: міста плюс центри областей, без повторів за назвою,
 * упорядковані українською. Місто має пріоритет над однойменним центром.
 */
export const ALL_PLACES: readonly Place[] = (() => {
  const seen = new Set(CITIES.map((c) => c.name));
  const merged = [...CITIES, ...OBLAST_CENTERS.filter((o) => !seen.has(o.name))];
  return merged.slice().sort((a, b) => a.name.localeCompare(b.name, "uk"));
})();
