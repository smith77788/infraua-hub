/**
 * Де ціль може бути ЗАРАЗ, а не де її бачили.
 *
 * ## Чому це головне
 *
 * Радар малює позначку там, де ціль зафіксували. Але між фіксом і екраном
 * лежить час: джерело збирає повідомлення, ми опитуємо його раз на хвилину,
 * людина відкриває карту ще пізніше. Поки все це відбувається, ціль летить.
 *
 * Це не теорія. Заміряно на живому фіді neptun.in.ua (24 цілі, 2026-09-16):
 *
 * | величина                        | медіана | p90    | максимум |
 * | ------------------------------- | ------- | ------ | -------- |
 * | вік запису (`updatedAt`)        | 205 с   | 262 с  | 326 с    |
 * | вік фікса (остання точка треку) | 205 с   | 433 с  | 674 с    |
 * | заявлений розкид позиції        | 4 км    | 10 км  | 25 км    |
 *
 * На типовій швидкості поршневого шахеда (185 км/год) медіанні 205 секунд —
 * це **10,5 км**. Тобто відстань, яку ціль пройшла, поки дані йшли до нас,
 * У 2,6 РАЗА БІЛЬША за коло невизначеності, яке ми малювали. А в найгіршому
 * заміряному випадку (674 с) — 34 км проти 4.
 *
 * Отже позначка на карті була не «тут ціль ±4 км», а «тут ціль була кілька
 * хвилин тому», подане як теперішнє. Це рівно та сама хиба, що й скрізь у
 * цьому проєкті: оцінене видають за заміряне. Тільки тут вона системна —
 * стосується кожної позначки на кожному екрані.
 *
 * ## Чому коло росте, а крапка не їде
 *
 * Спокуса очевидна: знаємо курс і швидкість — зсунемо позначку вперед. Так
 * роблять справжні радари (dead reckoning), і для них це правильно, бо в них
 * трек заміряний.
 *
 * Тут — ні. У тому самому заміряному зрізі `presumptiveCourse: true` стояв у
 * 21 цілі з 24: курс ПРИПУЩЕНИЙ джерелом, а не спостережений. Зсунути крапку
 * за припущеним курсом означає намалювати впевнене твердження про місце цілі,
 * побудоване на здогадці. Помилка тоді не зростає — вона переїжджає в інше
 * місце й виглядає там так само впевнено.
 *
 * Тому правило просте й одне:
 *
 * > **Розширити коло — це визнати незнання. Зсунути крапку — це стверджувати
 * > знання.** Зсуваємо лише те, що заміряли; розширюємо завжди.
 *
 * Крапка лишається там, де ціль БАЧИЛИ. Довкола неї — друге, більше коло: де
 * вона може бути тепер. Обидва підписані, і їх не можна сплутати.
 *
 * ## Що з цього йде в тривогу
 *
 * Найраніший край часу підльоту рахується від БЛИЖНЬОГО краю цього більшого
 * кола. Асиметрія та сама, що в усьому продукті: поспішити з попередженням
 * безпечно, запізнитися — ні.
 */

import type { Threat, ThreatType } from "./air";
import { SPEED_KMH, SPEED_RANGE_KMH } from "./threat-eta";
import { displayRadiusKm, EMPTY_QUALITY } from "./threat-quality";

/**
 * Стеля віку, після якої позначку не розтягуємо далі, а вважаємо втраченою.
 *
 * Без стелі коло росте необмежено, і ціль, яку джерело просто забуло закрити,
 * за годину накриває пів країни. Двадцять хвилин — це вже вдвічі більше за
 * найгірший заміряний фікс (674 с), тож жива ціль у стелю не впирається.
 */
export const MAX_DRIFT_MIN = 20;

/**
 * Коли зафіксовано САМУ ПОЗИЦІЮ.
 *
 * Не те саме, що «коли оновився запис», і різниця заміряна: `updatedAt`
 * оновлюється від будь-якої зміни (ще одне підтвердження, уточнення назви), а
 * позиція при цьому лишається тією, яку бачили раніше. У зрізі траплялись
 * записи, де `updatedAt` був на 412 секунд оптимістичніший за час останньої
 * точки треку — тобто майже сім хвилин застою, яких ніхто не бачив.
 *
 * Тому час беремо з останньої точки треку, коли вона є, і лише за її
 * відсутності — з `lastSeen`/`since`.
 */
export function fixedAtMs(t: Threat): number | null {
  const last = t.trail?.[t.trail.length - 1];
  if (last) {
    const ms = Date.parse(last.t);
    if (Number.isFinite(ms)) return ms;
  }
  for (const raw of [t.lastSeen, t.since]) {
    if (!raw) continue;
    const ms = Date.parse(raw);
    if (Number.isFinite(ms)) return ms;
  }
  return null;
}

/** Вік фікса, мс. `null` — джерело не сказало часу, і вигадувати його не можна. */
export function fixAgeMs(t: Threat, now: number): number | null {
  const at = fixedAtMs(t);
  if (at === null) return null;
  // Час із майбутнього — розбіжність годинників, а не політ назад.
  return Math.max(0, now - at);
}

export interface Drift {
  /** Вік фікса, секунди. `null` — невідомий. */
  ageSec: number | null;
  /** Найімовірніший зсув за цей час, км (типова швидкість класу). */
  likelyKm: number;
  /** Найбільший можливий зсув, км (швидкий край діапазону класу). */
  maxKm: number;
  /** Вік уперся в стелю — позначці більше не можна вірити як поточній. */
  capped: boolean;
}

/**
 * Скільки ціль могла пройти, поки дані йшли до нас.
 *
 * Два числа, і вони для різного. `likelyKm` — для картинки: коло, намальоване
 * за швидким краєм, на п'ятій хвилині накрило б область цілком, і карта
 * перестала б щось означати. `maxKm` — для тривоги: там питання не «де вона
 * найімовірніше», а «чи може вона вже бути в мене».
 */
export interface SpeedBelief {
  /** Найімовірніша швидкість, км/год. */
  likelyKmh: number;
  /** Найбільша правдоподібна швидкість, км/год. */
  fastKmh: number;
}

/**
 * У що ми віримо про швидкість цієї цілі, від найкращого джерела до найгіршого.
 *
 * Порядок тут і є вся суть. Заміряне завжди б'є припущене:
 *
 * 1. `measured` — швидкість, яку ми САМІ порахували з послідовних фіксів (свої
 *    опитування плюс трек джерела). Це вимір, і вилка в нього своя, вузька.
 * 2. `q.speedKmh` — швидкість, яку назвало джерело для цієї цілі.
 * 3. Таблиця класу — остання інстанція, і найширша: «шахед» покриває і 185
 *    км/год, і 600, бо канали пишуть про обидва однаково.
 *
 * Чому це важливо саме тут. Коло застою рахується зі швидкості, і якщо навіть
 * для цілі із ЗАМІРЯНИМ рухом брати класовий верх у 600 км/год, то за три
 * хвилини вона «може бути» за тридцять кілометрів у будь-який бік — і кожна
 * ціль у країні читається як «може бути вже поруч». Заміряно: так і виходило,
 * сорок відсотків сповіщень ставали одним і тим самим порожнім реченням.
 */
export function speedBelief(
  type: ThreatType | undefined,
  statedKmh: number | null,
  measured?: { speedKmh: number; speedSigma: number } | null | undefined,
): SpeedBelief {
  if (measured && measured.speedKmh > 0) {
    return {
      likelyKmh: measured.speedKmh,
      fastKmh: Math.max(measured.speedKmh, measured.speedKmh + Math.max(0, measured.speedSigma)),
    };
  }
  if (statedKmh !== null && statedKmh > 0) return { likelyKmh: statedKmh, fastKmh: statedKmh };
  const kind = type ?? "unknown";
  return { likelyKmh: SPEED_KMH[kind], fastKmh: SPEED_RANGE_KMH[kind][1] };
}

export function driftKm(
  type: ThreatType | undefined,
  ageMs: number | null,
  measuredKmh: number | null = null,
  measured?: { speedKmh: number; speedSigma: number } | null | undefined,
): Drift {
  if (ageMs === null) return { ageSec: null, likelyKm: 0, maxKm: 0, capped: false };
  const ageSec = Math.round(ageMs / 1000);
  const capMs = MAX_DRIFT_MIN * 60_000;
  const capped = ageMs > capMs;
  const hours = Math.min(ageMs, capMs) / 3_600_000;
  const belief = speedBelief(type, measuredKmh, measured);
  const likely = belief.likelyKmh;
  const fast = belief.fastKmh;
  return {
    ageSec,
    likelyKm: Math.round(likely * hours * 10) / 10,
    maxKm: Math.round(fast * hours * 10) / 10,
    capped,
  };
}

export interface NowRadius {
  /** Розкид позиції, як його називає джерело (або наша стеля), км. */
  statedKm: number;
  /** Найімовірніший зсув за час застою, км. */
  driftKm: number;
  /** Де ціль може бути найімовірніше: заявлене плюс зсув, км. */
  likelyKm: number;
  /**
   * Найбільше коло: заявлене плюс зсув за ШВИДКИМ краєм класу.
   *
   * Саме воно йде в найраніший край часу підльоту. Складаємо просто, а не
   * квадратично: квадратична сума правильна для двох незалежних ПОХИБОК, а тут
   * друга складова — не похибка, а реальний політ, який стався напевно.
   */
  maxKm: number;
  ageSec: number | null;
  capped: boolean;
}

/**
 * Коло «де ціль може бути зараз» для цієї позначки.
 *
 * `measured` — наш власний вимір руху (`track-filter`), коли він є. Передати
 * його сюди обовʼязково скрізь, де він доступний: інакше для цілі із
 * заміряною швидкістю коло рахувалось би класовим верхом, і вимір пропадав би
 * рівно там, де він найцінніший.
 */
export function nowRadiusKm(
  t: Threat,
  now: number,
  measured?: { speedKmh: number; speedSigma: number } | null | undefined,
): NowRadius {
  const q = t.quality ?? EMPTY_QUALITY;
  const stated = displayRadiusKm(q);
  const d = driftKm(t.type, fixAgeMs(t, now), q.speedKmh, measured);
  return {
    statedKm: stated,
    driftKm: d.likelyKm,
    likelyKm: Math.round((stated + d.likelyKm) * 10) / 10,
    maxKm: Math.round((stated + d.maxKm) * 10) / 10,
    ageSec: d.ageSec,
    capped: d.capped,
  };
}

/** Людською мовою: наскільки свіжа позиція. `null` — часу джерело не дало. */
export function fixAgeLabel(ageSec: number | null): string | null {
  if (ageSec === null) return null;
  if (ageSec < 45) return "щойно";
  const min = Math.round(ageSec / 60);
  if (min < 60) return `${min} хв тому`;
  const h = Math.floor(min / 60);
  return `${h} год ${min % 60} хв тому`;
}
