/**
 * Зліт носіїв: попередження за десять хвилин до того, як стане пізно.
 *
 * ## Найцінніші хвилини в усій системі
 *
 * Балістика долає Україну за лічені хвилини, і жодна оцінка траєкторії тут не
 * допоможе: коли ціль з'явилась у стрічці, часу вже немає. Але сам ПУСК має
 * попередника — зліт носія. Українські монітори роками передають це одне
 * повідомлення, і воно рятує більше, ніж уся решта разом: «злетів МіГ-31К,
 * готовність по всій країні».
 *
 * Ми ці повідомлення вже отримуємо: класифікатор типів має клас `aircraft`,
 * і саме в нього потрапляють «зліт», «пуск», «борт», «МіГ». Досі вони
 * розчинялись у загальному переліку цілей як «✈️ 1 борт» — тобто найважливіше
 * попередження виглядало як найменш важливе.
 *
 * ## Чому це попередження, а не тривога
 *
 * Зліт носія не означає пуск. Літак може відпрацювати й сісти. Тому текст
 * каже саме те, що сталося, і не вдає, що знає більше: «злетів носій —
 * готовність», а не «летить ракета».
 *
 * ## Межа
 *
 * Ми не бачимо ні аеродромів, ні самих літаків: ми бачимо повідомлення про
 * них. Точніше — тільки з даними, яких у відкритих джерелах немає.
 */

import type { Threat, ThreatType } from "./air";

/** Скільки попередження лишається чинним без підтвердження. */
export const CARRIER_WARNING_TTL_MS = 60 * 60 * 1000;

/**
 * Чи це повідомлення про носія балістики.
 *
 * Тип `aircraft` сам по собі замалий: у нього ж потрапляє звичайна тактична
 * авіація, про яку попереджати всю країну не можна — інакше попередження
 * знеціниться рівно до того, як знадобиться.
 */
const CARRIER_TEXT = /міг-?31|mig-?31|кинджал|кинжал|ту-?95|ту-?160|ту-?22|носі[йя]/i;

export interface CarrierWarning {
  /** Що саме побачили — словами джерела, без домислів. */
  what: string;
  at: number;
  /** Скільки джерел сказали те саме. */
  reports: number;
}

export function detectCarrier(threats: readonly Threat[], now: number): CarrierWarning | null {
  const hits = threats.filter((t) => {
    const type: ThreatType = t.type ?? "unknown";
    if (type !== "aircraft") return false;
    return CARRIER_TEXT.test(`${t.name} ${t.source}`);
  });
  if (hits.length === 0) return null;
  const reports = hits.reduce((n, t) => n + (t.reports ?? 1), 0);
  return { what: hits[0]!.name, at: now, reports };
}

export function warningIsFresh(w: CarrierWarning | null, now: number): boolean {
  return w !== null && now - w.at < CARRIER_WARNING_TTL_MS;
}

/**
 * Текст попередження.
 *
 * Друге речення — найважливіше в ньому. Людина, яка прочитає «готовність» і
 * піде спати, нічого не втратить; людина, яка прочитає «летить ракета» і
 * побіжить в укриття на годину, наступного разу не побіжить узагалі.
 */
export function renderCarrierWarning(w: CarrierWarning): string {
  return [
    "✈️ <b>Зліт носія — готовність по країні</b>",
    "",
    `Джерела повідомляють: ${w.what}.`,
    "",
    "Пуску ще НЕ БУЛО. Це попередження, щоб ви встигли: від пуску балістики до влучання — хвилини, і тоді попереджати вже пізно.",
    "",
    "<i>Тримайте телефон поруч. Якщо буде пуск — напишемо окремо.</i>",
  ].join("\n");
}
