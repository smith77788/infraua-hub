/**
 * Погодне вікно для БпЛА — «льотна ніч».
 *
 * Шахеди літають не за будь-якої погоди, і це не таємне знання: сильний вітер
 * збиває малий апарат із курсу й садить пуски, дощ і мокрий сніг гасять оптику
 * й псують двигун, а от низька суцільна хмарність і штиль — навпаки, ідеальні:
 * апарат стабільний, а з землі його не видно мобільним вогневим групам, які
 * б'ють по ньому візуально з прожектором і кулеметом.
 *
 * Тому «сьогодні льотна погода» — це реальний, дешевий сигнал, якого не дає
 * жоден монітор цілей: він каже не «що в небі ЗАРАЗ», а «наскільки ймовірним
 * буде масований захід дронів найближчим вечором». Люди планують за ним ніч —
 * лягати спати чи тримати валізу біля дверей.
 *
 * Це ОЦІНКА СПРИЯТЛИВОСТІ, а не прогноз атаки: погода дозволяє або заважає, але
 * рішення про пуск — не наша змінна. Так це й підписано.
 *
 * Чиста, безстанова функція — рахується з наявних метеоданих, тестується без
 * мережі.
 */

export interface DroneWeatherInput {
  /** Швидкість приземного вітру, км/год. */
  windKmh: number;
  /** Опади, мм за годину (дощ/сніг). */
  precipMm: number;
  /** Хмарність, % (0–100). Необовʼязкова — не всі джерела її дають. */
  cloudPct?: number | undefined;
  /** Температура повітря, °C. Необовʼязкова: сильний мороз саджає ресурс. */
  tempC?: number | undefined;
}

/** Наскільки погода СПРИЯЄ заходу ударних БпЛА. */
export type DroneWeatherBand = "favorable" | "mixed" | "adverse";

export interface DroneWeatherVerdict {
  /** 0..100 — вище означає сприятливіше для дронів (гірше для нас). */
  score: number;
  band: DroneWeatherBand;
  /** Один рядок людською мовою. */
  label: string;
  /** Що саме зважило — щоб оцінка не була чорною скринькою. */
  reasons: string[];
  /** Межа чесності: погода дозволяє, а не оголошує атаку. */
  caveat: string;
}

const CAVEAT =
  "Це оцінка сприятливості погоди для БпЛА, а не прогноз атаки. Погода лише " +
  "дозволяє або заважає — рішення про пуски ухвалює не вона.";

const BAND_LABEL: Record<DroneWeatherBand, string> = {
  favorable: "льотна погода — сприяє заходу дронів",
  mixed: "погода змінна — частковий вплив на дрони",
  adverse: "нельотна погода — умови проти дронів",
};

/**
 * Зводить метеодані в оцінку «льотної ночі».
 *
 * Починаємо від нейтральних 50 і рухаємось у той чи інший бік. Ваги підібрано
 * так, щоб жоден єдиний чинник не давав крайнього вердикту сам по собі: штиль
 * без інших даних — ще не «льотна ніч», а буря — майже напевно проти дронів.
 */
export function droneWeather(input: DroneWeatherInput): DroneWeatherVerdict {
  const reasons: string[] = [];
  let score = 50;

  // Вітер — головний чинник. Штиль сприяє, шторм саджає малий апарат.
  const wind = Math.max(0, input.windKmh);
  if (wind < 12) {
    score += 22;
    reasons.push(`слабкий вітер ${Math.round(wind)} км/год — стабільний політ`);
  } else if (wind < 25) {
    score += 6;
    reasons.push(`помірний вітер ${Math.round(wind)} км/год`);
  } else if (wind < 40) {
    score -= 18;
    reasons.push(`сильний вітер ${Math.round(wind)} км/год — збиває з курсу`);
  } else {
    score -= 34;
    reasons.push(`штормовий вітер ${Math.round(wind)} км/год — проти малих БпЛА`);
  }

  // Опади гасять оптику й псують політ.
  if (input.precipMm > 1.5) {
    score -= 24;
    reasons.push(`опади ${input.precipMm.toFixed(1)} мм/год — нельотні умови`);
  } else if (input.precipMm > 0.2) {
    score -= 10;
    reasons.push("слабкі опади");
  } else {
    score += 6;
    reasons.push("без опадів");
  }

  // Хмарність ХОВАЄ дрон від візуального перехоплення з землі.
  if (input.cloudPct != null) {
    if (input.cloudPct >= 70) {
      score += 16;
      reasons.push(
        `суцільна хмарність ${Math.round(input.cloudPct)}% — прикриття від вогневих груп`,
      );
    } else if (input.cloudPct <= 25) {
      score -= 10;
      reasons.push(`чисте небо ${Math.round(input.cloudPct)}% — дрон видно з землі`);
    }
  }

  // Сильний мороз саджає ресурс поршневого двигуна й батарей. Помірний ефект.
  if (input.tempC != null && input.tempC <= -10) {
    score -= 8;
    reasons.push(`мороз ${Math.round(input.tempC)}°C — знижений ресурс`);
  }

  score = Math.max(0, Math.min(100, Math.round(score)));
  const band: DroneWeatherBand = score >= 66 ? "favorable" : score >= 40 ? "mixed" : "adverse";
  return { score, band, label: BAND_LABEL[band], reasons, caveat: CAVEAT };
}
