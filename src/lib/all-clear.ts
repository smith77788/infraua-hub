/**
 * Особистий відбій: «можна виходити» — і скільки це тривало.
 *
 * ## Чому це окрема річ, а не дзеркало тривоги
 *
 * Уся ніша побудована навколо початку: сирена, ціль, укриття. Але людина в
 * коридорі чекає протилежного — сигналу, що все скінчилось. І саме цього
 * сигналу їй ніхто не дає: офіційний відбій треба піти й перевірити самому, а
 * монітори мовчать, бо «немає новин — немає поста».
 *
 * Мовчання після тривоги має рівно ту саму ціну, що й пропущене попередження:
 * люди або сидять в укритті довше, ніж треба, або виходять навмання й
 * перестають ховатися взагалі.
 *
 * ## Правило, яке не можна порушувати
 *
 * Поспішити з ПОПЕРЕДЖЕННЯМ безпечно: найгірше, що станеться, — людина дарма
 * зайде в коридор. Поспішити з ВІДБОЄМ смертельно: вона вийде, коли ще летить.
 *
 * Тому відбій НЕ виводиться з нашої картини неба. Порожнє небо в OSINT означає
 * лише те, що ніхто нічого не бачить, — а не те, що загрози немає. Відбій
 * чекає на ОФІЦІЙНЕ скасування тривоги, і жодна інша умова його не замінює.
 *
 * ## Що ми додаємо понад офіційне
 *
 * Офіційне оголошення каже «відбій». Воно не каже, скільки ви просиділи, чи
 * була це найдовша тривога місяця і чи варто лягати спати. Це й додаємо — те,
 * що людині потрібно рівно в цю хвилину й чого більше ніхто не рахує.
 */

export interface AllClearDecision {
  send: boolean;
  reason: string;
  /** Скільки тривала тривога, хв. */
  durationMin: number;
}

/**
 * Чи казати «можна виходити».
 *
 * `wasAlerted` — чи ми взагалі турбували цю людину за цю тривогу. Відбій тому,
 * кого ми не попереджали, — це повідомлення про подію, якої для нього не було:
 * він дізнається про тривогу з відбою, і це гірше, ніж мовчання.
 */
export function decideAllClear(opts: {
  officialActive: boolean;
  alarmSince: number | null | undefined;
  wasAlerted: boolean;
  now: number;
}): AllClearDecision {
  const { officialActive, alarmSince, wasAlerted, now } = opts;
  const durationMin = alarmSince ? Math.max(0, Math.round((now - alarmSince) / 60_000)) : 0;

  if (officialActive) {
    return { send: false, reason: "офіційна тривога триває", durationMin };
  }
  if (!alarmSince) {
    return { send: false, reason: "тривоги не було", durationMin: 0 };
  }
  if (!wasAlerted) {
    // Дізнатися про тривогу з відбою — гірше за мовчання.
    return { send: false, reason: "ми не турбували цю людину за цю тривогу", durationMin };
  }
  return { send: true, reason: "офіційний відбій", durationMin };
}

function duration(min: number): string {
  if (min < 1) return "менше хвилини";
  if (min < 60) return `${min} хв`;
  const h = Math.floor(min / 60);
  const m = min % 60;
  return m ? `${h} год ${String(m).padStart(2, "0")} хв` : `${h} год`;
}

/**
 * Текст відбою.
 *
 * Найважливіше — перший рядок: людина в коридорі читає одне слово й приймає
 * рішення. Далі тривалість, бо саме її ніхто не рахує, а вона відповідає на
 * «чи варто вже лягати».
 *
 * Джерело названо прямо: це відбій ПОВІТРЯНИХ СИЛ, а не наш висновок. Якби ми
 * дали власний відбій і помилились, ціна була б не в довірі, а в людях.
 */
export function renderPersonalAllClear(
  durationMin: number,
  opts: { longestThisMonth?: boolean } = {},
): string {
  const lines = [
    "🟢 <b>Відбій — можна виходити</b>",
    "",
    `Тривога тривала <b>${duration(durationMin)}</b>.`,
  ];
  if (opts.longestThisMonth && durationMin >= 60) {
    lines.push("Це найдовша ваша тривога цього місяця.");
  }
  lines.push("");
  lines.push(
    "<i>Відбій оголосили Повітряні Сили — це не наш висновок. Ми не даємо відбою за власною картиною неба: порожньо в OSINT означає лише, що ніхто нічого не бачить.</i>",
  );
  return lines.join("\n");
}
