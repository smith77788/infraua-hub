/**
 * «У мами тривога» — те, через що люди насправді не сплять.
 *
 * ## Чого не закриває персональний радар
 *
 * Над людиною може бути тихо, а вона не спатиме, бо тривога в іншому місті — у
 * матері, у дитини в гуртожитку, у чоловіка у відрядженні. Зараз єдиний спосіб
 * це знати — читати чужі обласні канали або дзвонити. Обидва погані: перший
 * шумить, другий будить того, за кого хвилюєшся.
 *
 * Коло рідних у боті вже є — воно вміє «я в порядку» після удару. Але це
 * відповідь ПІСЛЯ. Тут — до: коли в області когось із кола оголошують тривогу,
 * решта кола дізнається одним рядком, нікого не розбудивши.
 *
 * ## Межі, узяті свідомо
 *
 * • **Жодних координат.** Повідомляється область, а не точка: «У мами тривога —
 *   Сумщина». Місце розташування рідних лишається їхнім.
 * • **Один рядок, не потік.** Про початок і про відбій — і все. Хвиля, цілі,
 *   курси — це вже нав'язування чужої тривоги, від якої людина нічим не
 *   допоможе.
 * • **Мовчання не тлумачиться** — як і скрізь у колі: відсутність відмітки не
 *   означає біди.
 */

export interface CircleAlertTarget {
  /** Кому повідомити. */
  chatId: number;
  /**
   * Про кого — УСІ разом, одним переліком.
   *
   * Не по одному імені на запис, і це не дрібниця оформлення. Родина майже
   * завжди живе в одному місті: якщо в Харкові четверо рідних, то єдиний, хто
   * у Львові, дістав би чотири повідомлення підряд про ОДНУ сирену. Саме так і
   * вчаться не читати повідомлення взагалі — а наступне може бути про нього.
   */
  aboutNames: string[];
  oblast: string;
}

export interface CircleMemberPlace {
  chatId: number;
  name: string;
  oblasts: string[];
  /**
   * Чи людина поставила сповіщення на паузу (`/stop`).
   *
   * Обовʼязкове поле, а не необовʼязкове: «забув передати» тут означає «мовчки
   * порушив обіцянку», а такий недогляд не має бути можливим непомітно.
   *
   * Важливо, що пауза стосується лише ОТРИМАННЯ. Той, хто поставив паузу, усе
   * одно лишається тим, ПРО КОГО кажуть рідним: він вимкнув свої сповіщення,
   * а не зник із кола.
   */
  muted: boolean;
}

/**
 * Кому з кола розіслати звістку про тривогу в чужій області.
 *
 * Сам той, у кого тривога, сюди не потрапляє: він і так отримає власне
 * сповіщення, а друге — про себе ж, у третій особі — виглядало б як помилка.
 */
export function circleAlertTargets(
  members: readonly CircleMemberPlace[],
  oblast: string,
): CircleAlertTarget[] {
  const affected = members.filter((m) => m.oblasts.includes(oblast));
  if (affected.length === 0) return [];
  const out: CircleAlertTarget[] = [];
  for (const watcher of members) {
    // `/stop` обіцяє «сповіщення на паузі» — без цього рядка обіцянка була
    // порожньою саме для кола, тобто для найчастішого нічного повідомлення.
    if (watcher.muted) continue;
    // Якщо у спостерігача тривога в тій самій області, він уже знає — і рядок
    // «у мами тривога» під власною сиреною лише заважає. Перевірка стосується
    // спостерігача, тож стоїть тут, а не всередині перебору рідних.
    if (watcher.oblasts.includes(oblast)) continue;
    const names = affected.filter((w) => w.chatId !== watcher.chatId).map((w) => w.name);
    if (names.length === 0) continue;
    out.push({ chatId: watcher.chatId, aboutNames: names, oblast });
  }
  return out;
}

/**
 * Імена екрануються, і це не педантизм.
 *
 * Імʼя в колі задає сама людина (`/circle імʼя ...`). Незекранована кутова
 * дужка ламає HTML, і Telegram відхиляє повідомлення ЦІЛКОМ — тобто звістка
 * про тривогу в рідних не доходить узагалі. Найгірший наслідок тут не
 * підроблений текст, а тиша.
 *
 * Ця сама вада вже була в `circle.ts` (запис 29 у findings) і повернулась тут
 * разом із новим модулем — тож межа тепер під тестом.
 */
function safe(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function renderRelativeAlarm(names: readonly string[], oblast: string): string {
  return `🔴 <b>Тривога в рідних</b> · ${names.map(safe).join(", ")} — ${safe(oblast)}`;
}

export function renderRelativeClear(names: readonly string[], oblast: string): string {
  return `🟢 <b>Відбій у рідних</b> · ${names.map(safe).join(", ")} — ${safe(oblast)}`;
}
