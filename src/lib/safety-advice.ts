/**
 * Що робити прямо зараз — і чому це різне для різних цілей.
 *
 * ## Знання, якого в людей немає
 *
 * Монітори кажуть, ЩО летить. Ніхто не каже, що з цим робити, — і це не
 * дрібниця, бо дії відрізняються радикально:
 *
 *  • **балістика** — від пуску до влучання хвилини, а часто секунди. Бігти
 *    кудись уже пізно: правило двох стін, геть від вікон, лягти;
 *  • **шахед** — чутно заздалегідь, час є. Встигаєш дійти до укриття, і саме
 *    тому йти треба, а не «переждати в коридорі»;
 *  • **КАБ** — прилітає без попередження й б'є по прифронтових містах. Головна
 *    небезпека — скло: вибухова хвиля вибиває вікна на сотні метрів;
 *  • **крилата ракета** — летить довго й низько, маршрут петляє. Час є, але
 *    «пройшла повз» не означає «не повернеться».
 *
 * Це не поради з інтернету: це прямі наслідки часу підльоту й способу
 * ураження, тобто того самого, що система вже рахує. Тому вони й живуть тут, а
 * не в тексті-заглушці.
 *
 * ## Межа
 *
 * Тут немає нічого, чого не знає рятувальник. Це не заміна офіційних правил і
 * не інструкція для конкретної будівлі — це те, що людині треба згадати за
 * дві секунди, коли телефон світить їй в обличчя о третій ночі.
 */

import type { ThreatType } from "./air";

export interface SafetyAdvice {
  /** Один рядок, який читається першим. */
  headline: string;
  /** Кроки — не більше трьох: четвертий уже не прочитають. */
  steps: string[];
  /** Скільки часу зазвичай є. Формулювання чесне: це не гарантія. */
  timing: string;
}

