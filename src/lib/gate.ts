/**
 * Гейт підписки: радар працює для тих, хто в каналі.
 *
 * Рішення продуктове, і воно свідоме: канал і бот — це одне ціле, канал дає
 * загальну картину, бот — персональну, і людина, яка користується другим, має
 * бачити перше.
 *
 * Але це інструмент безпеки, тож у самій конструкції закладені три запобіжники,
 * і жоден із них не можна прибрати «для простоти»:
 *
 *  1. **Гейт відмовляє у бік доступу, а не відмови.** Не вдалося перевірити
 *     членство (Telegram не відповів, бот не адміністратор каналу, канал не
 *     налаштований) — пускаємо. Збій на нашому боці не має коштувати комусь
 *     сповіщення про ціль.
 *  2. **`/stop` ніколи не гейтиться.** Можливість вимкнути сповіщення не може
 *     залежати ні від чого: людина має право замовкнути бота будь-коли.
 *  3. **Уже налаштовані сповіщення не вимикаються заднім числом.** Якщо людина
 *     задала точку й потім вийшла з каналу, розсилка триває. Тихо перестати
 *     попереджати того, кого вже попереджали, — це найгірший спосіб карати за
 *     відписку.
 *
 * Тут — лише чисті рішення й тексти; мережеві виклики в сервері.
 */

/** Статуси, які Telegram віддає в `getChatMember`. */
export type ChatMemberStatus =
  "creator" | "administrator" | "member" | "restricted" | "left" | "kicked";

/**
 * Чи людина в каналі.
 *
 * `restricted` окремо: цей статус означає «у чаті, але обмежений», і сам по
 * собі членства не доводить — його доводить прапорець `is_member`. Прирівняти
 * його до «в каналі» означало б пускати тих, кого з каналу фактично вигнали.
 */
export function isSubscribed(status: string | undefined, isMember?: boolean): boolean {
  if (status === "creator" || status === "administrator" || status === "member") return true;
  if (status === "restricted") return isMember === true;
  return false;
}

/** Публічне посилання на канал із `@username`. Числовий id посилання не дає. */
export function channelUrl(channelId: string | undefined): string | null {
  const raw = channelId?.trim();
  if (!raw) return null;
  if (raw.startsWith("@")) return `https://t.me/${raw.slice(1)}`;
  if (/^https:\/\/t\.me\//.test(raw)) return raw;
  return null;
}

/**
 * Екран «підпишіться».
 *
 * Пояснює ПРИЧИНУ, а не ставить умову. «Підпишіться, щоб користуватись» без
 * причини читається як здирництво й відштовхує рівно тих, кому воно потрібне;
 * «канал дає загальну картину, бот — вашу особисту» — це те, що є насправді.
 */
export function renderGate(url: string): string {
  return [
    "📡 <b>Спершу підпишіться на канал</b>",
    "",
    "Канал і радар — одне ціле: у каналі загальна картина по країні, у боті — те, що йде саме на вашу точку. Без каналу ви побачите половину.",
    "",
    `<a href="${url}">Відкрити канал</a> → підписатись → повернутись і натиснути «Я підписався».`,
    "",
    "<i>Перевіряємо лише факт підписки. Нічого іншого про вас канал не знає.</i>",
  ].join("\n");
}

export const GATE_ACTION = "sub:check";

export function gateKeyboard(url: string): {
  inline_keyboard: ({ text: string; url: string } | { text: string; callback_data: string })[][];
} {
  return {
    inline_keyboard: [
      [{ text: "📡 Підписатись на канал", url }],
      [{ text: "✅ Я підписався", callback_data: GATE_ACTION }],
    ],
  };
}

/** Відповідь на «Я підписався», коли підписки все ще немає. */
export function renderStillNotSubscribed(): string {
  return "Поки не бачу вас у каналі. Підпишіться й натисніть ще раз — інколи Telegram оновлює це з затримкою в кілька секунд.";
}
