/**
 * Передтривога: попередження ДО сирени — і чому тут можна поспішати.
 *
 * Це дзеркало правила про відбій, і разом вони утворюють одну симетрію, на
 * якій тримається вся чесність системи:
 *
 *   • ПОСПІШИТИ З ПОПЕРЕДЖЕННЯМ безпечно. Найгірше, що станеться, — людина
 *     дарма зайде в коридор на кілька хвилин раніше.
 *   • ПОСПІШИТИ З ВІДБОЄМ смертельно. Людина вийде з укриття, коли ще летить.
 *
 * Тому відбій чекає на офіційне оголошення, а попередження — ні. OSINT-монітори
 * регулярно бачать ціль раніше, ніж вмикається сирена: між фіксацією курсу й
 * офіційною тривогою минають хвилини, і саме ці хвилини — те єдине, чим тут
 * узагалі можна допомогти.
 *
 * Але передтривога МУСИТЬ називати себе передтривогою. «Тривога!» від нас там,
 * де офіційної немає, — це підміна повноважень: людина вирішить, що оголосили
 * офіційно, і згодом не повірить справжній сирені.
 *
 * Окремо тут живе замір випередження: коли офіційну тривогу нарешті
 * оголошують, ми знаємо, наскільки раніше попередили — і кажемо це числом.
 * Не обіцянкою «ми швидші», а заміряним фактом по кожному конкретному разу.
 */

import { oblastKey } from "./alert-levels";

/** Стан офіційної тривоги над точкою на момент нашого попередження. */
export type AlertPhase = "pre" | "official" | "unknown";

/**
 * Порівнюємо за ключем області, а не за рядком.
 *
 * Це запобіжник, а не виправлення збою: наразі обидві сторони короткі
 * («Рівненщина»), бо `parseOfficialAlerts` зводить назви джерела через
 * `shortOblastName`. Але та згортка живе в одному конкретному джерелі, і
 * сусідній шлях — рівні небезпеки з `neptun` — саме на цьому й поламався:
 * там назви лишились офіційними, і порівняння не збіглося ні разу (див.
 * `oblastKey` в `alert-levels.ts`). Тож тут порівняння від форми назви більше
 * не залежить.
 */
export function alertPhase(official: readonly string[] | null, oblast: string): AlertPhase {
  if (official === null) return "unknown";
  const key = oblastKey(oblast);
  return official.some((o) => oblastKey(o) === key) ? "official" : "pre";
}

/** Скільки хвилин ми випередили офіційне оголошення. */
export function leadMinutes(preAlertAt: number, officialAt: number): number {
  return Math.max(0, Math.round((officialAt - preAlertAt) / 60_000));
}

/**
 * Чи варто взагалі казати про випередження.
 *
 * Менше за хвилину — це не випередження, а збіг, і хвалитися ним означає
 * привчати читача до того, що наші числа декоративні. Понад пів години —
 * майже напевно не наша заслуга, а те, що тривогу оголосили з іншої причини.
 */
export function leadWorthTelling(minutes: number): boolean {
  return minutes >= 1 && minutes <= 30;
}

/** Шапка передтривоги. Головне слово — «ЩЕ НЕ ОГОЛОШЕНА». */
export function preAlertHeader(): string {
  return "⚠️ <b>ПЕРЕДТРИВОГА</b> — офіційну ще не оголошували";
}

export function preAlertFooter(): string {
  return (
    "<i>ми бачимо ціль на вашому напрямку раніше за сирену. Це наше попередження, " +
    "а не офіційна тривога — коли її оголосять, ми напишемо окремо.</i>"
  );
}

/**
 * Підтвердження: офіційну оголосили, і ось наскільки ми випередили.
 *
 * Найпереконливіше повідомлення в усьому боті — бо воно не обіцяє, а
 * звітується. І воно ж найлегше перетворюється на брехню, якщо рахувати
 * випередження від чогось іншого, ніж момент нашого попередження.
 */
export function renderOfficialConfirmed(oblast: string, minutes: number | null): string {
  const lines = [`🔴 <b>Офіційну тривогу оголошено</b> — ${oblast}`];
  if (minutes !== null && leadWorthTelling(minutes)) {
    lines.push("");
    lines.push(`Ми попередили вас на <b>${minutes} хв</b> раніше за сирену.`);
  }
  lines.push("");
  lines.push("<i>Далі — за офіційними вказівками. Відбій ми дамо лише після офіційного.</i>");
  return lines.join("\n");
}
