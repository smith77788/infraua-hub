/**
 * Наскільки можна вірити повідомленню — і чому саме настільки.
 *
 * У консолі кілька десятків OSINT-каналів, і досі всі важили однаково: позначка
 * з одного загального новинного каналу давала той самий рівень, що й позначка,
 * яку одночасно дали три канали спостереження при активній офіційній тривозі.
 * Це не дрібниця в бік обережності — це рівно та помилка, через яку операційні
 * сповіщення перестають читати: коли все «критичне», критичного немає.
 *
 * ## Чому саме код Адміралтейства
 *
 * Це стандартна шкала НАТО (STANAG 2511) з двох незалежних осей: **надійність
 * джерела** (A–F) і **достовірність відомості** (1–6). Дві осі, а не одна,
 * тому що надійне джерело може передати чутку, а сумнівне — сказати правду, і
 * зведення цього в одне число втрачає обидва факти. Шкала стара, вживана і
 * зрозуміла всім, хто працює з розвідданими, — це рівно та властивість, якої
 * варто хотіти від оцінки, що потрапляє на екран чергового.
 *
 * ## Чого тут навмисно немає
 *
 * **Оцінок конкретних каналів**, виставлених мною. Присвоїти реальному
 * медіа-ресурсу бал довіри — це твердження про нього, і воно потребувало б
 * підстав, яких у мене немає. Тому надійність виводиться лише з двох речей,
 * і обидві перевіряються:
 *
 * - **роль каналу в самому переліку** — він доданий як канал спостереження за
 *   повітряною обстановкою, як регіональний чи як загальний новинний. Це
 *   структурний факт про наш список, а не судження про якість видання: канал,
 *   що веде спостереження, повідомляє первинне, загальноновинний — переказує;
 * - **підтвердження** — скільки **незалежних** джерел сказали те саме, і чи
 *   збігається це з офіційною тривогою. Це вимірюється, а не оцінюється.
 *
 * Підтвердження робить основну роботу навмисно: три перекази одного джерела —
 * це одне повідомлення, а не три, і саме тут ця різниця зникає найчастіше.
 */

/** Роль каналу в переліку консолі. Структурний факт, не оцінка видання. */
export type SourceRole = "watch" | "regional" | "general" | "official" | "unknown";

/**
 * Надійність джерела за Адміралтейством, звужена до тих значень, які ми
 * справді можемо обґрунтувати. `A` не використовується: «повністю надійне»
 * означає тривалу історію без жодної помилки, а такої підстави в нас немає ні
 * для кого.
 */
export type Reliability = "B" | "C" | "D" | "F";

/** Достовірність відомості за Адміралтейством. */
export type Credibility = 1 | 2 | 3 | 5 | 6;

export interface CredibilityAssessment {
  reliability: Reliability;
  credibility: Credibility;
  /** Наприклад «C3». Те, що йде в підпис поруч із позначкою. */
  code: string;
  /** Скільки незалежних джерел, після відкидання переказів того самого. */
  independentSources: number;
  /** Чому саме така оцінка — по рядку на кожну підставу. */
  reasons: string[];
}

const RELIABILITY_LABEL: Record<Reliability, string> = {
  B: "зазвичай надійне",
  C: "досить надійне",
  D: "не завжди надійне",
  F: "надійність невідома",
};

const CREDIBILITY_LABEL: Record<Credibility, string> = {
  1: "підтверджено іншими джерелами",
  2: "ймовірно правдиве",
  3: "можливо правдиве",
  5: "малоймовірне",
  6: "оцінити неможливо",
};

export function describeCode(assessment: CredibilityAssessment): string {
  return `${assessment.code} — ${RELIABILITY_LABEL[assessment.reliability]}, ${CREDIBILITY_LABEL[assessment.credibility]}`;
}

export interface CredibilityInput {
  /** Джерела, що дали це повідомлення. Повтори того самого не рахуються двічі. */
  sources: readonly string[];
  /** Роль кожного джерела; невідомі трактуються як `unknown`. */
  roleOf: (source: string) => SourceRole;
  /** Чи збігається повідомлення з активною офіційною тривогою в тому ж районі. */
  officialCorroboration?: boolean;
  /**
   * Скільки повідомлень стоїть за позначкою всього. Разом із кількістю
   * незалежних джерел це показує переказ: десять повідомлень від одного
   * джерела — це одне джерело.
   */
  reports?: number;
}

/**
 * Оцінює одну позначку.
 *
 * Надійність береться за **найкращою** роллю серед джерел: якщо серед них є
 * канал спостереження, повідомлення прийшло від нього, а решта могла його
 * переказати. Достовірність — за підтвердженням, і тут офіційна тривога
 * важить як окреме джерело, бо вона й є окреме джерело: не OSINT, а держава.
 */
export function assessCredibility(input: CredibilityInput): CredibilityAssessment {
  const distinct = Array.from(new Set(input.sources.filter(Boolean)));
  const roles = distinct.map(input.roleOf);
  const reasons: string[] = [];

  const hasWatch = roles.includes("watch");
  const hasRegional = roles.includes("regional");
  const hasOfficial = roles.includes("official");

  let reliability: Reliability;
  if (hasOfficial) {
    reliability = "B";
    reasons.push("серед джерел є офіційне");
  } else if (hasWatch) {
    reliability = "C";
    reasons.push(
      "є канал спостереження за повітряною обстановкою — первинне повідомлення, не переказ",
    );
  } else if (hasRegional) {
    reliability = "D";
    reasons.push("лише регіональні канали — первинне спостереження не підтверджене");
  } else if (roles.some((role) => role === "general")) {
    reliability = "D";
    reasons.push("лише загальні новинні канали — вони зазвичай переказують");
  } else {
    // Невідома роль — це саме невідомість, а не поганий канал. Розрізняти їх
    // обовʼязково: інакше кожне джерело поза нашим переліком мовчки
    // прирівнювалося б до найгіршого.
    reliability = "F";
    reasons.push(distinct.length > 0 ? "роль джерела невідома" : "джерело не назване");
  }

  // Офіційна тривога — незалежна вісь підтвердження, тому рахується як
  // окреме джерело, а не як ще один канал.
  const independent = distinct.length + (input.officialCorroboration ? 1 : 0);

  let credibility: Credibility;
  if (independent >= 3) {
    credibility = 1;
    reasons.push(`${independent} незалежних підтверджень`);
  } else if (independent === 2) {
    credibility = 2;
    reasons.push("два незалежні підтвердження");
  } else if (independent === 1) {
    credibility = 3;
    reasons.push("одне джерело, без незалежного підтвердження");
  } else {
    credibility = 6;
    reasons.push("підтвердити нічим");
  }

  const reports = input.reports ?? distinct.length;
  if (reports > distinct.length && distinct.length === 1) {
    // Це найчастіший спосіб, у який один слух виглядає як подія: тому
    // сказано прямо, а не пораховано в бали.
    reasons.push(`${reports} повідомлень від одного джерела — це одне джерело, а не ${reports}`);
  }

  if (input.officialCorroboration) reasons.push("збігається з активною офіційною тривогою");

  return {
    reliability,
    credibility,
    code: `${reliability}${credibility}`,
    independentSources: independent,
    reasons,
  };
}

/**
 * Чи достатньо підстав, щоб піднімати рівень тривоги за цією позначкою.
 *
 * ## Напрямок відмови тут протилежний до решти системи
 *
 * У контролі доступу сумнів вирішується відмовою: не показати зайве дешевше,
 * ніж показати таємне. У попередженні про повітряну загрозу все навпаки —
 * пропущений удар коштує більше, ніж зайва тривога. Тому рівень **знижується
 * лише за наявності підстав**, а не за їх відсутності.
 *
 * Підстава рівно одна: ми **знаємо**, що джерело в нашому переліку є таким,
 * що зазвичай переказує (регіональний чи загальний, без жодного каналу
 * спостереження), **і** повідомлення ніхто незалежно не підтвердив. Невідома
 * роль підставою не є: це невідомість, а не погана якість, і мовчки
 * прирівнювати одне до одного означало б глушити все, що приходить із-поза
 * нашого списку.
 */
export function warrantsEscalation(assessment: CredibilityAssessment): boolean {
  if (assessment.credibility >= 5 && assessment.reliability !== "F") return false;
  return !(assessment.reliability === "D" && assessment.credibility >= 3);
}
