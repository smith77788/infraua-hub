import { useEffect, useRef, type ReactNode } from "react";

/**
 * Розкладка накладок над картою.
 *
 * ## Навіщо окремий шар
 *
 * Кожна накладка раніше позиціювала себе САМА: `bottom-24`, `bottom-[46px]`,
 * `left-14 top-2`. Жодна з них не знала, що ще зараз на екрані, тож числа були
 * припущеннями про сусідів — «плеєр заввишки 46 пікселів», «реплей точно є».
 * Щойно припущення не справджувалось (реплею немає, банер зʼявився, текст
 * переніс рядок), блоки налазили один на одного. Полагодити це, підправивши
 * число, неможливо: кожна нова накладка ламає розрахунок наступної, і саме
 * тому дефект повертався після кожного виправлення.
 *
 * Тут накладки не позиціюються взагалі. Вони лежать у звичайному потоці
 * всередині смуг, а смуги розставлені один раз. Потік не вміє накладати
 * елементи один на одного — тож перекриття стає неможливим за побудовою, а не
 * за уважністю того, хто додає наступний блок.
 *
 * ## Чому смуги, а не сітка
 *
 * Накладки різної ширини й зʼявляються незалежно. Ряд угорі з трьох колонок
 * (ліва, середина, права) розводить їх і по вертикалі, і по горизонталі:
 * колонка росте вниз, а сусідні не перетинає ніколи.
 *
 * ## Відступ для елементів керування Leaflet
 *
 * Нижні смуги непрозорі й закрили б атрибуцію карти — а її приховувати не
 * можна, це умова використання джерела. Тому висота смуг вимірюється й
 * віддається карті як `--map-bottom-inset`: атрибуція й кнопки масштабу
 * піднімаються рівно настільки, скільки смуги займають ЗАРАЗ. Стала тут не
 * підходить — реплей нальоту то є, то немає.
 */
/**
 * Бічні відступи під елементи керування Leaflet.
 *
 * Значення — у `--map-ctrl-*` (див. `styles.css`), тут лише піврядка проміжку,
 * щоб накладка не торкалась кнопки впритул.
 */
const SIDE_PAD =
  "pl-[calc(var(--map-ctrl-left,44px)+0.5rem)] pr-[calc(var(--map-ctrl-right,58px)+0.5rem)]";

export interface MapOverlaysProps {
  /** Ліва колонка згори: панелі, які читають, а не лише дивляться. */
  topLeft?: ReactNode;
  /** Середина згори: банери стану — вузькі, короткоживучі. */
  topCenter?: ReactNode;
  /** Права колонка згори. */
  topRight?: ReactNode;
  /** Знизу ліворуч: легенда та інше, що розгортається вгору. */
  bottomLeft?: ReactNode;
  /** Знизу по центру: чипи-підсумки. */
  bottomCenter?: ReactNode;
  /** Смуги на всю ширину: плеєр часу, реплей. Ідуть найнижче. */
  bars?: ReactNode;
}

export default function MapOverlays({
  topLeft,
  topCenter,
  topRight,
  bottomLeft,
  bottomCenter,
  bars,
}: MapOverlaysProps) {
  const barsRef = useRef<HTMLDivElement>(null);

  /*
   * Міряємо САМЕ смуги, а не всю нижню колонку.
   *
   * Спершу вимірювалась колонка цілком — і розгорнута легенда (до 70% висоти
   * екрана) роздувала відступ так, що атрибуція виїжджала за верх карти.
   * Заміряно: 642 px відступу на екрані 320 px. Відступ має відповідати тому,
   * що стоїть унизу ЗАВЖДИ, а не тому, що людина щойно відкрила й зараз закриє.
   *
   * ResizeObserver, а не вимір при монтуванні: висота смуг змінюється і від
   * появи реплею, і від ширини екрана — підписи переносяться.
   */
  useEffect(() => {
    const node = barsRef.current;
    if (!node) return;
    const host = node.closest(".relative") ?? node.parentElement?.parentElement;
    if (!(host instanceof HTMLElement)) return;
    const apply = () => {
      host.style.setProperty("--map-bottom-inset", `${Math.round(node.offsetHeight)}px`);
    };
    apply();
    if (typeof ResizeObserver === "undefined") return;
    const observer = new ResizeObserver(apply);
    observer.observe(node);
    return () => {
      observer.disconnect();
      host.style.removeProperty("--map-bottom-inset");
    };
  }, []);

  return (
    <>
      {/*
        Відступи з боків лишають місце елементам керування Leaflet: кнопки
        масштабу в лівому верхньому куті, перемикач підкладки — у правому. Вони
        не в потоці, тож розвести їх можна лише відступом, а числа беремо з
        `--map-ctrl-*` — заміряні там, де ті елементи й стилізуються.
      */}
      {/*
        Смуга має ВИЗНАЧЕНУ висоту — від `top-2` до нижніх смуг, — щоб панелі
        могли обмежитись нею (`max-h-full`) і прокручуватись усередині. Без
        цього панель хвиль на великому нальоті (заміряно на 136 шахедах)
        виростала нижче за карту й накривала плеєр часу. Межа береться з тієї ж
        виміряної `--map-bottom-inset`, тож розійтися з реальністю не може.
      */}
      <div
        className={`pointer-events-none absolute inset-x-0 top-2 z-[600] flex items-start gap-2 ${SIDE_PAD}`}
        style={{ bottom: "calc(var(--map-bottom-inset, 3rem) + 0.5rem)" }}
      >
        <div className="flex h-full min-h-0 min-w-0 flex-col items-start gap-2">{topLeft}</div>
        <div className="flex h-full min-h-0 min-w-0 flex-1 flex-col items-center gap-1.5">
          {topCenter}
        </div>
        <div className="flex h-full min-h-0 min-w-0 flex-col items-end gap-2">{topRight}</div>
      </div>

      {/*
        Нижній шар розтягнутий на всю карту (`inset-0`), а вміст притиснутий
        донизу (`justify-end`). Так ряд накладок отримує ВИЗНАЧЕНУ висоту —
        рівно карта мінус смуги, — і розгорнута легенда може обмежитись нею
        (`max-h-full`). Доти легенда міряла себе від висоти ЕКРАНА (70svh) і на
        невисокій карті вилазила поверх шапки сторінки.

        Порожня частина шару прозора й не ловить кліки, тож карта під нею
        тягнеться й масштабується як раніше.
      */}
      <div className="pointer-events-none absolute inset-0 z-[600] flex flex-col justify-end gap-1.5">
        {/*
          Легенда — окрема смуга, і вона НЕ ділить рядок із чипом.
          
          Спершу вони стояли поруч із `flex-wrap`. На вузькому екрані чип
          переносився на другий рядок — і там `h-full` (потрібний, щоб легенда
          могла обмежитись висотою карти) починав рахуватись від висоти всього
          контейнера, а не свого рядка. Заміряно: колонка чипа звисала на 343 px
          нижче за карту. Два прийоми, кожен правильний окремо, разом не
          працюють — тож переносу тут немає взагалі.

          `flex-1 min-h-0` дає смузі ВИЗНАЧЕНУ висоту (карта мінус усе інше), і
          саме від неї легенда рахує свій `max-h-full`. `justify-end` тримає
          вміст унизу, тож закрита легенда лишається там, де й була.
        */}
        <div className={`flex min-h-0 flex-1 flex-col items-start justify-end ${SIDE_PAD}`}>
          {bottomLeft}
        </div>
        {/*
          Чип гарячих областей і смуги міряються РАЗОМ як «нижнє, що є завжди»:
          верхня смуга спиняється над ними (`--map-bottom-inset`), а не заходить
          на них. Саме тому відкрита панель шарів більше не накриває чип і
          легенду знизу. Легенда (bottomLeft) свідомо ПОЗА виміром: вона
          розгортається до 70% висоти й роздула б відступ (див. коментар вище),
          тож для неї лишається запас, а не точний вимір.

          Чипу віддано весь рядок: брак ширини різав назви областей
          («Херсонщина 2» → «Херсо…»).
        */}
        <div ref={barsRef} className="flex flex-col gap-1.5">
          <div className={`flex flex-col items-center gap-1.5 ${SIDE_PAD}`}>{bottomCenter}</div>
          {bars}
        </div>
      </div>
    </>
  );
}
